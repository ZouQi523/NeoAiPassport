#!/usr/bin/env python3
"""Build the game's small, uncompressed LVGL 9 font from a licensed TTF subset."""
import argparse
import hashlib
import json
import re
import struct
import urllib.parse
import urllib.request
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/fonts'


def inventory():
    text = (ROOT / 'main/bomb_text.h').read_text()
    strings = [json.loads(s) for s in re.findall(r'"[^"\n]*"', text)]
    return sorted(set(''.join(strings) + ''.join(chr(n) for n in range(32, 127))))


def has_glyph(data, codepoint):
    """Check the actual TTF cmap; a tofu bitmap must never pass coverage."""
    u16 = lambda off: struct.unpack_from('>H', data, off)[0]
    u32 = lambda off: struct.unpack_from('>I', data, off)[0]
    cmap = None
    for i in range(u16(4)):
        off = 12 + i * 16
        if data[off:off + 4] == b'cmap': cmap = u32(off + 8)
    if cmap is None: return False
    for i in range(u16(cmap + 2)):
        off = cmap + u32(cmap + 4 + i * 8 + 4)
        form = u16(off)
        if form == 4 and codepoint <= 0xffff:
            count = u16(off + 6) // 2
            ends = off + 14
            starts = ends + count * 2 + 2
            deltas = starts + count * 2
            ranges = deltas + count * 2
            for j in range(count):
                start, end = u16(starts + 2*j), u16(ends + 2*j)
                if start <= codepoint <= end:
                    delta, shift = u16(deltas + 2*j), u16(ranges + 2*j)
                    if shift == 0: return (codepoint + delta) % 65536 != 0
                    glyph = u16(ranges + 2*j + shift + 2*(codepoint - start))
                    return glyph != 0 and (glyph + delta) % 65536 != 0
        elif form == 12:
            for j in range(u32(off + 12)):
                start, end, first = struct.unpack_from('>III', data, off + 16 + j*12)
                if start <= codepoint <= end: return first + codepoint - start != 0
    return False


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fetch', action='store_true', help='fetch the public Google Fonts subset and OFL')
    args = parser.parse_args()
    ASSETS.mkdir(parents=True, exist_ok=True)
    chars = inventory()
    source = ASSETS / 'bomb-ui-subset.ttf'
    if args.fetch:
        css_url = 'https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@400&text=' + urllib.parse.quote(''.join(chars))
        css = urllib.request.urlopen(css_url, timeout=60).read().decode()
        url = re.search(r'url\((https:[^)]+)\)', css)[1]
        source.write_bytes(urllib.request.urlopen(url, timeout=60).read())
        (ASSETS / 'OFL.txt').write_bytes(urllib.request.urlopen('https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssc/OFL.txt', timeout=60).read())
        (ASSETS / 'bomb-font-source.json').write_text(json.dumps({'family': 'Noto Sans SC Regular', 'css_url': css_url, 'font_url': url, 'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'license': 'SIL OFL 1.1'}, indent=2) + '\n')
    data = source.read_bytes()
    missing = [c for c in chars if not has_glyph(data, ord(c))]
    if missing: raise SystemExit('Source font missing: ' + ''.join(missing))
    assert not has_glyph(data, 0x9f98), 'Negative coverage control must remain absent'
    font = ImageFont.truetype(str(source), 18)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    descriptors = ['    {0},']
    proof = []
    for char in chars:
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        width, height = right-left, bottom-top
        image = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -top), char, font=font, anchor='ls', fill=255)
        values = [round(v*15/255) for v in image.getdata()] if width and height else []
        start = len(bitmap)
        # LVGL PLAIN 4bpp uses high nibble first, no padding between rows.
        for n in range(0, len(values), 2):
            bitmap.append((values[n] << 4) | (values[n+1] if n+1 < len(values) else 0))
        decoded = []
        for byte in bitmap[start:]: decoded.extend((byte >> 4, byte & 15))
        assert decoded[:len(values)] == values
        descriptors.append(f'    {{.bitmap_index={start}, .adv_w={round(font.getlength(char)*16)}, .box_w={width}, .box_h={height}, .ofs_x={left}, .ofs_y={-bottom}}}, /* U+{ord(char):04X} */')
        proof.append({'codepoint': ord(char), 'bitmap_index': start, 'width': width, 'height': height, 'pixels_sha256': hashlib.sha256(bytes(values)).hexdigest()})
    rows = ['    ' + ', '.join(f'0x{x:02x}' for x in bitmap[n:n+16]) + ',' for n in range(0, len(bitmap), 16)]
    offsets = ', '.join(str(ord(c)-32) for c in chars)
    code = '''/* Generated by tools/generate_bomb_font.py. Font data: SIL OFL 1.1; see OFL.txt.
 * Copyright 2014-2021 Adobe. Derived from Noto Sans SC; application font name: Bomb UI.
 */
#include "lvgl.h"
static const uint8_t glyph_bitmap[] = {\n''' + '\n'.join(rows) + '\n};\n'
    code += 'static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n' + '\n'.join(descriptors) + '\n};\n'
    code += 'static const uint16_t unicode_list[] = {' + offsets + '};\n'
    code += f'''static const lv_font_fmt_txt_cmap_t cmaps[] = {{{{
    .range_start=32, .range_length={ord(chars[-1])-31}, .glyph_id_start=1,
    .unicode_list=unicode_list, .glyph_id_ofs_list=NULL, .list_length={len(chars)},
    .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}}}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap=glyph_bitmap, .glyph_dsc=glyph_dsc, .cmaps=cmaps,
    .kern_dsc=NULL, .kern_scale=0, .cmap_num=1, .bpp=4,
    .kern_classes=0, .bitmap_format=LV_FONT_FMT_TXT_PLAIN, .stride=0
}};
const lv_font_t bomb_font_18 = {{
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height={ascent+descent}, .base_line={descent},
    .subpx=LV_FONT_SUBPX_NONE, .underline_position=-2, .underline_thickness=1,
    .dsc=&font_dsc
}};
'''
    (ASSETS / 'bomb_font_18.c').write_text(code)
    (ASSETS / 'bomb-font-inventory.json').write_text(json.dumps({'size_px': 18, 'bpp': 4, 'line_height': ascent+descent, 'baseline': descent, 'pillow': pillow_version, 'source_sha256': hashlib.sha256(data).hexdigest(), 'bitmap_sha256': hashlib.sha256(bitmap).hexdigest(), 'glyphs': proof}, indent=2) + '\n')
    print(f'Bomb UI font: {len(chars)} glyphs, {len(bitmap)} bitmap bytes, source cmap and 4bpp pixels verified; Pillow {pillow_version}')


if __name__ == '__main__': main()
